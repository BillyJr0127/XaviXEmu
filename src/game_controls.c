uint32_t xavix_takecopter_ir_code(int forward, int backward,
	int left, int right)
{
	static const uint32_t serial_codes[16] =
	{
		UINT32_C(0x0199e667), UINT32_C(0x0199e001),
		UINT32_C(0x019987ff), UINT32_C(0x01999999),
		UINT32_C(0x01986679), UINT32_C(0x0198601f),
		UINT32_C(0x019807e1), UINT32_C(0x01981987),
		UINT32_C(0x0181e787), UINT32_C(0x0181e1e1),
		UINT32_C(0x0181861f), UINT32_C(0x01819879),
		UINT32_C(0x01866799), UINT32_C(0x018661ff),
		UINT32_C(0x01860601), UINT32_C(0x01861867)
	};
	unsigned longitudinal = 0;
	unsigned lateral = 0;

	/* ROM dynamics confirm that decoded bits $01/$04 are forward/backward
	 * acceleration, while $10/$40 are left/right steering. */
	if (forward && backward)
		longitudinal = 3;
	else if (backward)
		longitudinal = 1;
	else if (forward)
		longitudinal = 2;
	if (left && right)
		lateral = 3;
	else if (right)
		lateral = 1;
	else if (left)
		lateral = 2;
	return serial_codes[longitudinal * 4 + lateral];
}

