const xavix_game_control_profile *xavix_game_control_profile_for_kind(
	enum drgqst_rom_kind kind)
{
	size_t index;
	for (index = 0; index < sizeof(GAME_CONTROL_PROFILES) /
		sizeof(GAME_CONTROL_PROFILES[0]); ++index)
	{
		if (GAME_CONTROL_PROFILES[index].kind == kind)
			return &GAME_CONTROL_PROFILES[index];
	}
	return NULL;
}

int xavix_game_control_action_visible(const xavix_game_control_profile *profile,
	enum xavix_controller_action action)
{
	return profile && action >= 0 && action < XAVIX_CONTROLLER_ACTION_COUNT &&
		profile->actions[action] != XAVIX_GAME_CONTROL_NONE;
}

size_t xavix_game_control_profile_count(void)
{
	return sizeof(GAME_CONTROL_PROFILES) / sizeof(GAME_CONTROL_PROFILES[0]);
}

const xavix_game_control_profile *xavix_game_control_profile_at(size_t index)
{
	return index < xavix_game_control_profile_count() ?
		&GAME_CONTROL_PROFILES[index] : NULL;
}

